import numpy as np, xarray as xr
ds = xr.open_dataset('/work/tmp/sample.nc', engine='h5netcdf')
lat = ds['latitude'].values.astype(np.float64)
lon = ds['longitude'].values.astype(np.float64)
print('lat dtype', ds['latitude'].dtype, 'lon dtype', ds['longitude'].dtype)
print('lat[0:5]', lat[:5], '... around 55.66-55.70:')
i = np.searchsorted(lat, 55.6)
print(lat[i-2:i+6])
print('around 56.86-56.90:')
j = np.searchsorted(lat, 56.8)
print(lat[j-2:j+6])
print('lon around 16.44-16.48:')
k = np.searchsorted(lon, 16.4)
print(lon[k-2:k+6])
print('lon around 17.62-17.68:')
m = np.searchsorted(lon, 17.6)
print(lon[m-2:m+6])

latm = (lat >= 55.67) & (lat <= 56.87)
lonm = (lon >= 16.45) & (lon <= 17.65)
print('n lat in region:', latm.sum(), lat[latm][0], '->', lat[latm][-1])
print('n lon in region:', lonm.sum(), lon[lonm][0], '->', lon[lonm][-1])

sst = ds['analysed_sst']
print('sst dtype', sst.dtype, 'encoding:', {k:v for k,v in sst.encoding.items()})
sub = sst.isel(time=0).sel(latitude=slice(lat[latm][0], lat[latm][-1]), longitude=slice(lon[lonm][0], lon[lonm][-1])).values
print('region sub shape', sub.shape)
print('finite frac:', np.isfinite(sub).mean(), 'min/max:', np.nanmin(sub), np.nanmax(sub))
print('units attr:', sst.attrs.get('units'), '| standard_name:', sst.attrs.get('standard_name'))
print('global comment:', ds.attrs.get('comment'))
print('time encoding:', ds.time.encoding)
print('time value:', ds.time.values)
# check a row/col pattern of NaN (land)
print('nan count per lat row (first 10):', np.isnan(sub).sum(axis=1)[:10])
print('nan count per lon col (first 10):', np.isnan(sub).sum(axis=0)[:10])
