
import fsspec, xarray as xr, numpy as np, time
fs = fsspec.filesystem('onedata')
f = fs.open('/icsa2027_data_20261101T090944Z/s2z/sst_s2.nc', 'rb')
ds = xr.open_dataset(f, engine='h5netcdf')
print("time[0], time[-1]:", ds.time.values[0], ds.time.values[-1])
lat = np.asarray(ds.latitude.values, dtype=np.float64)
lon = np.asarray(ds.longitude.values, dtype=np.float64)
print("lat:", float(lat[0]), float(lat[-1]), "n=", len(lat))
print("lon:", float(lon[0]), float(lon[-1]), "n=", len(lon))
latm = (lat >= 58.69) & (lat <= 59.89)
lonm = (lon >= 18.69) & (lon <= 19.89)
print("region lat:", lat[latm][0], lat[latm][-1], "n=", int(latm.sum()))
print("region lon:", lon[lonm][0], lon[lonm][-1], "n=", int(lonm.sum()))
print("units:", ds.analysed_sst.attrs.get('units'))
print("comment:", ds.attrs.get('comment'))
t0 = time.time()
i0 = int(np.searchsorted(ds.time.values, np.datetime64('1992-01-01')))
print("idx 1992-01-01:", i0, ds.time.values[i0])
chunk = ds.analysed_sst.isel(time=i0, latitude=np.where(latm)[0], longitude=np.where(lonm)[0]).values
print("read time:", time.time()-t0, "s; chunk:", chunk.shape, chunk.dtype, "finite:", int(np.isfinite(chunk).sum()))
print("sample values (K):", chunk.ravel()[:8])
ds.close()
